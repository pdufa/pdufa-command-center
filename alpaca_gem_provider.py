"""Read-only Alpaca market-data provider for active GEM and GEM JR programs.

Uses completed split-adjusted daily OHLCV. Source and clinical gating remain
separate. Raw Alpaca bars are reported as provider observations, NOT certified
historical GEM backtest evidence. No brokerage orders, watchlist writes or
brokerage trade instructions are generated by this module.
"""
from __future__ import annotations

import json
import math
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

from alpaca_connection import load_paper_credentials
from scripts.fetch_gem_2025_alpaca_review import request_bars
from scripts.alpaca_gem_daily_monitor import market_snapshot, clean_bars, evaluate

ET = ZoneInfo("America/New_York")
MAX_TRACKED = 80


def current_completed_session(now=None):
    """Reject intraday partial bars; US closing data at least 60m after 4pm ET."""
    now = (now or datetime.now(ET)).astimezone(ET)
    d = now.date() if now.hour >= 17 else now.date()-timedelta(days=1)
    while d.weekday() >= 5:
        d -= timedelta(days=1)
    return d


def active_stage_programs(path="data/gem_stage_membership.json"):
    """Preserve exact-program references; never assume ticker == clinical trial."""
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError):
        return []
    items=[]
    for stage in ("GEM", "GEM_JR"):
        for key, row in data.get("stages",{}).get(stage,{}).get("entries",{}).items():
            if not isinstance(row,dict) or row.get("status")!="ACTIVE":
                continue
            ticker=str(row.get("ticker") or "").strip().upper()
            if not ticker or not ticker.replace(".","").replace("-","").isalnum():
                continue
            items.append({"stage":stage,"ticker":ticker,
                          "exact_program":row.get("exact_program") or key,
                          "drug":row.get("drug") or "",
                          "pdufa_date":row.get("pdufa_date") or ""})
    return items[:MAX_TRACKED]


def read_source_verified_events(path="data/post_phase3_historical_trade_events.csv"):
    """Only full source-date records can unlock GEM entry readiness."""
    import csv
    try:
        with Path(path).open(newline="",encoding="utf-8") as f:
            return list(csv.DictReader(f))
    except (OSError, UnicodeError):
        return []


def provider_bars(symbol, *, credentials, feed="sip", now=None, fetch=None,
                  lookback_days=220):
    if feed not in {"sip","iex"}:
        raise ValueError("Only official Alpaca SIP or IEX feeds are allowed")
    cutoff=current_completed_session(now)
    start=(cutoff-timedelta(days=lookback_days)).isoformat()
    end=(cutoff+timedelta(days=1)).isoformat()
    bars=request_bars(symbol,start,end,cutoff.isoformat(),
                      credentials[0],credentials[1],feed=feed,fetch=fetch)
    bars=[r for r in bars if date.fromisoformat(r["session"])<=cutoff]
    return bars,cutoff


def rsi14(bars):
    """Wilder's 14-day RSI from 15+ completed daily closes."""
    if len(bars)<15:
        return None
    closes=[x["close"] for x in bars]
    gains=[max(closes[i]-closes[i-1],0) for i in range(1,len(closes))]
    losses=[max(closes[i-1]-closes[i],0) for i in range(1,len(closes))]
    a,b=sum(gains[:14])/14,sum(losses[:14])/14
    for g,l in zip(gains[14:],losses[14:]):
        a=(a*13+g)/14
        b=(b*13+l)/14
    if b==0:
        return 100. if a>0 else 50.
    return round(100-100/(1+a/b),2)


def assess_symbol(symbol, *, credentials, verified_events=None,
                  paper_positions=None, feed="sip", now=None, fetch=None):
    """Return actual chart numbers AND independently evidence-gated signal."""
    bars,cutoff=provider_bars(symbol,credentials=credentials,
                             feed=feed,now=now,fetch=fetch)
    candles=clean_bars(bars)
    if not candles:
        return {"ticker":symbol, "provider":"ALPACA", "feed":feed,
                "alert":"DATA_BLOCKED", "reason":"INSUFFICIENT_VALID_DAILY_BARS",
                "bars_count":len(bars), "as_of":cutoff.isoformat(),
                "trading_orders_placed":0}
    snap=market_snapshot(candles)
    if not snap:
        return {"ticker":symbol, "provider":"ALPACA", "feed":feed,
                "alert":"DATA_BLOCKED", "reason":"INDICATORS_UNAVAILABLE",
                "bars_count":len(candles), "as_of":cutoff.isoformat(),
                "trading_orders_placed":0}
    result=evaluate(symbol,bars,verified_events or {},paper_positions or {},
                    today=cutoff,feed=feed)
    if result.get("stage")=="DATA_BLOCKED":
        result["alert"]="DATA_BLOCKED"
    result.update({"provider":"ALPACA","feed":feed,
                   "as_of":candles[-1]["session"].isoformat(),
                   "bars_count":len(candles),
                   "rsi14":rsi14(candles),
                   "adjustment":"split",
                   "historical_source_audit":"PENDING",
                   "source_coverage":"IEX_SINGLE_EXCHANGE" if feed=="iex"
                     else "SIP_CONSOLIDATED",
                   "trading_orders_placed":0})
    # Never claim a position when no broker positions were supplied.
    result["position_scope"]="PAPER_ALPACA_ONLY" if paper_positions is not None else "NOT_CONNECTED"
    return result


def render_provider_panel(stage, root="data"):
    """Optional on-demand Streamlit chart metrics directly under each GEM page."""
    import streamlit as st
    from urllib.error import HTTPError
    stage_code="GEM_JR" if stage in {"GEM JR", "GEM_JR"} else "GEM"
    programs=[p for p in active_stage_programs(
        Path(root)/"gem_stage_membership.json") if p["stage"]==stage_code]
    heading="GEM JR" if stage_code=="GEM_JR" else "GEM"
    with st.expander(f"ALPACA DAILY MARKET DATA — {heading}",expanded=False):
        st.caption(
            "Alpaca is the market-data provider. Read-only EOD historical bars; "
            "no trades. Technical entry setups are provisional; two validated "
            "GEM financing/clinical benchmarks remain mandatory.")
        st.write(f"Active exact programs: {len(programs)}")
        if not programs:
            st.info("No active programs in saved membership.")
            return
        credentials,error=load_paper_credentials(st.secrets)
        if error:
            st.warning(error)
            st.caption("Add paper credentials in Streamlit app Secrets, not in a chat or source file.")
            return
        symbols=sorted({p["ticker"] for p in programs})
        selected=st.selectbox("Stock ticker",symbols,key=f"alpaca_symbol_{stage}")
        feed=st.selectbox("Historical market feed",
                          ["sip","iex"],index=0,
                          format_func=lambda x:
                          "SIP (consolidated daily, preferred)" if x=="sip"
                          else "IEX (single-exchange, review only)",
                          key=f"alpaca_feed_{stage}")
        if st.button("REFRESH ALPACA DAILY SIGNAL",key=f"alpaca_refresh_{stage}"):
            try:
                result=assess_symbol(selected,credentials=credentials,
                    verified_events=read_source_verified_events(
                        Path(root)/"post_phase3_historical_trade_events.csv"),
                    feed=feed)
                st.session_state[f"alpaca_result_{stage}"]=result
            except HTTPError as exc:
                st.session_state[f"alpaca_result_{stage}"]={
                    "ticker":selected,"alert":"DATA_BLOCKED",
                    "reason":f"ALPACA_ACCESS_DENIED_OR_FAILED_HTTP_{exc.code}",
                    "provider":"ALPACA","feed":feed}
            except (OSError,RuntimeError,ValueError,KeyError,TypeError):
                st.session_state[f"alpaca_result_{stage}"]={
                    "ticker":selected,"alert":"DATA_BLOCKED",
                    "reason":"ALPACA_API_OR_PRICE_VALIDATION_FAILED",
                    "provider":"ALPACA","feed":feed}
        result=st.session_state.get(f"alpaca_result_{stage}")
        if not result or result.get("ticker")!=selected or result.get("feed")!=feed:
            st.info("Select a ticker and refresh to request Alpaca data.")
            return
        alert=result.get("alert","DATA_BLOCKED")
        if alert in {"ENTRY_SETUP_NEXT_OPEN_RECHECK","ENTRY_SETUP_REVIEW"}:
            st.warning(f"PROVISIONAL ENTRY SETUP: {alert}. No verified BUY or broker order.")
        elif alert=="EXIT_WARNING":
            st.error("PAPER POSITION EXIT WARNING: "+str(result.get("reason","")))
        else:
            st.info(f"Status: {alert} — {result.get('reason','')}")
        snap=result.get("technical") or {}
        if snap:
            cols=st.columns(4)
            for col,(key,label) in zip(cols,[
                ("close","Close ($)"),("sma20","SMA20 ($)"),
                ("atr14","ATR14 ($)"),("rvol20","RVOL20 (×)")]):
                col.metric(label,snap.get(key,"—"))
            st.caption(
                f"As of {result.get('as_of','—')} | "
                f"Feed: {feed.upper()} | RSI14: {result.get('rsi14','—')} | "
                f"SMA50: {snap.get('sma50','—')} | "
                f"Base high: {snap.get('base_high','—')} | "
                f"Base low: {snap.get('base_low','—')} | "
                f"Provisional stop: {snap.get('provisional_stop','—')} | "
                f"Entry score preview: {result.get('entry_score_preview','—')}")
        st.caption(
            "IEX volume excludes other exchanges. Alpaca market observations "
            "do not themselves verify Phase 3, both completed financings, "
            "PDUFA timing, positions at other brokers, or live execution. "
            "Historical trading returns remain unvalidated.")
