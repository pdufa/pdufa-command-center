const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const roster=JSON.parse(fs.readFileSync(path.join(root,"data/p3PostDataActive.json"),"utf8"));
const read=p=>fs.readFileSync(path.join(root,p),"utf8");

test("all-FOCUS source endpoint uses exact canonical FOCUS roster and source-only diagnostics",()=>{
  assert.equal(roster.records.length,32);
  assert.equal(new Set(roster.records.map(x=>x.nct)).size,32);
  const route=read("app/api/predictions/roster-source-scan/route.ts");
  assert.match(route,/FOCUS_SPECIALTY_ASSESSMENT_QUEUE/);
  assert.match(route,/makeEvidenceRun\(study,nct,"FULL"\)/);
  assert.match(route,/clinicaltrials\.gov\/api\/v2\/studies\//);
  assert.match(route,/MAX_RESPONSE_BYTES/);
  assert.match(route,/SOURCE_TIMEOUT_MS/);
  assert.match(route,/CONCURRENCY/);
  assert.match(route,/Exact NCT record did not match/);
  assert.match(route,/sourceUnavailable:failed.length/);
  assert.match(route,/independentlyCompletedScientificReviews:0/);
  assert.match(route,/calibratedFDAForecasts:0/);
  assert.match(route,/savedToDatabase:false/);
  assert.match(route,/ABSTAIN/);
  assert.match(route,/NOT_VALIDATED/);
  assert.match(route,/req.nextUrl.searchParams.get\("run"\)!=="source-inspection"/);
  assert.match(route,/Origin header required/);
  assert.match(route,/export async function POST/);
  assert.match(route,/export async function GET/);
  assert.doesNotMatch(route,/writeFile|INSERT INTO|UPDATE |DELETE FROM|probability:\s*[0-9]/);
});
test("production predictions page offers an explicit full-roster button without auto-run",()=>{
  const page=read("app/predictions/page.tsx");
  const ui=read("app/predictions/FullRosterSourceScan.tsx");
  assert.match(page,/<FullRosterSourceScan\/>/);
  assert.match(ui,/Start Full FOCUS Scan — 29 Trials/);
  assert.match(ui,/method:"POST"/);
  assert.match(ui,/onClick=\{\(\)=>void start\(\)\}/);
  assert.match(ui,/Download scan results/);
  assert.match(ui,/savedSnapshot as unknown as Response/);
  const scan=JSON.parse(read("data/focus-29-registry-source-scan-20261108.json"));
  assert.equal(scan.kind,"FOCUS_29_TRIAL_SOURCE_INSPECTION_NOT_VALIDATED_FDA_ASSESSMENT");
  assert.equal(scan.summary.targetTrials,29);
  assert.equal(scan.summary.sourceScanned,29);
  assert.equal(scan.summary.sourceUnavailable,0);
  assert.equal(scan.summary.independentlyCompletedScientificReviews,0);
  assert.equal(scan.summary.calibratedFDAForecasts,0);
  assert.equal(scan.summary.savedToDatabase,false);
  const archivedNcts=new Set(scan.rows.map(row=>row.nct));
  assert.equal(archivedNcts.size,29);
  assert.ok(scan.rows.every(row=>roster.records.some(r=>r.nct===row.nct)));
  assert.deepEqual(roster.records.filter(row=>!archivedNcts.has(row.nct)).map(row=>row.nct).sort(),["NCT05031780","NCT06553768","NCT06747468"],"Do not rewrite the historical 29-trial scan to claim retrieval of later additions");
  assert.ok(scan.rows.every(row=>row.tests.length===12&&row.prediction==="ABSTAIN"&&row.certainty==="NOT_VALIDATED"));
  assert.match(ui,/SOURCE_SCANNED/);
  assert.match(ui,/Review required · ABSTAIN/);
  assert.match(ui,/not automatically stored in the medical database/);
  assert.doesNotMatch(ui,/useEffect|setInterval|onLoad|approvalProbability:\s*\d/);
});
