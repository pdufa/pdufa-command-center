 assert.equal(archived.records.filter(x=>x.clinicalFive.score!==null).length,15);
 const canary=archived.records.find(r=>r.nct==="NCT06081894");
 assert.equal(canary.clinicalFive.score,45);
 assert.equal(canary.clinicalFive.scoredFactors,5);
 assert.equal(canary.clinicalFive.graded.length,5);
 assert.match(schema,/APPROVAL.*CRL.*REVIEW_DELAY/);
