const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const api=fs.readFileSync(path.join(root,"app/api/predictions/medical-method-audit/route.ts"),"utf8");
const validator=fs.readFileSync(path.join(root,"lib/medical-method-audit.ts"),"utf8");
const monitor=fs.readFileSync(path.join(root,"app/predictions/assessment/PilotMethodAuditMonitor.tsx"),"utf8");
const parent=fs.readFileSync(path.join(root,"app/predictions/assessment/LivePredictionMonitor.tsx"),"utf8");
const backend=fs.readFileSync(path.resolve(__dirname,"../../backend/app/medical_method_audit_worker.py"),"utf8");
const server=fs.readFileSync(path.resolve(__dirname,"../../backend/app/main.py"),"utf8");

test("pilot audit endpoints are authenticated, exact-NCT and strongly split by read vs write key",()=>{
  assert.match(api,/hasSession/);
  assert.match(api,/authConfigured/);
  assert.match(api,/if\(nct!=="NCT06081894"\)/);
  assert.match(api,/if\(req\.headers\.get\("origin"\)!==req\.nextUrl\.origin\)/);
  assert.match(api,/PDUFA_MEDICAL_REVIEW_API_BASE_URL/);
  assert.doesNotMatch(api,/PDUFA_API_BASE_URL/);
  assert.match(api,/method==="GET"\?/);
  assert.match(api,/PDUFA_MEDICAL_REVIEW_READ_KEY/);
  assert.match(api,/PDUFA_MEDICAL_INTERNAL_API_KEY/);
  assert.match(api,/\/api\/internal\/medical-method-audit\//);
  assert.match(api,/validatePilotMethodAudit/);
  assert.match(api,/export async function GET/);
  assert.match(api,/export async function POST/);
  assert.match(api,/detail==="No recorded pilot audit"/);
});
test("800-position job is source classification only and cannot produce FDA outcomes or clinical grade events",()=>{
  assert.match(validator,/x\.totalPositions!==800/);
  assert.match(validator,/x\.scientificReviewEventsWritten!==0\|\|x\.gradeEventsWritten!==0/);
  assert.match(validator,/pred\.APPROVAL!=="ABSTAIN"/);
  assert.match(validator,/x\.accuracy!=="NOT_CALIBRATED"/);
  assert.match(validator,/x\.completedAssessmentGroups!==Math\.floor\(x\.completedPositions\/20\)/);
  assert.match(validator,/MISSING_SOURCE_AUDIT_EVENTS/);
  assert.match(backend,/auditKind/);
  assert.match(backend,/SAVED_TRIAGE_SOURCE_CLASSIFICATION_VERIFICATION/);
  assert.match(backend,/gradeEventsWritten":0/);
  assert.match(backend,/scientificReviewEventsWritten":0/);
  assert.match(backend,/for start in range\(done,TOTAL,20\)/);
  assert.match(backend,/ON CONFLICT\(run_id,position_index\) DO NOTHING/);
  assert.doesNotMatch(backend,/INSERT INTO medical_assessment_review_events/);
  assert.doesNotMatch(backend,/INSERT INTO medical_assessment_phase_events/);
  assert.match(server,/PDUFA_MEDICAL_METHOD_AUDIT_ENABLED/);
  assert.match(server,/require_medical_internal_key, require_medical_method_audit_storage/);
});
test("source audit is explicitly started; no GET starts a worker, no simulated method progress",()=>{
  assert.match(monitor,/fetch\("\/api\/predictions\/medical-method-audit\?nct="/);
  assert.match(monitor,/method:"POST"/);
  assert.match(monitor,/Start 800-position source audit/);
  assert.match(monitor,/run\?\.status==="COMPLETE"/);
  assert.match(monitor,/onClick=\{\(\)=>void startAudit\(\)\}/);
  assert.match(monitor,/source classifications/);
  assert.match(monitor,/does not assign clinical grades or calculate FDA probabilities/);
  assert.match(monitor,/window\.setInterval/);
  assert.match(monitor,/document\.visibilityState==="visible"/);
  assert.match(monitor,/pollRef\.current\?\.\(\)/);
  assert.match(monitor,/not the 800-method scientific scoring/);
  assert.match(parent,/<PilotMethodAuditMonitor nct=\{nct\}\/>/);
  assert.match(parent,/NOT CALIBRATED/);
  assert.match(parent,/ABSTAIN/);
});
