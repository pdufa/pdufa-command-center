def canonical_bytes(payload: dict[str, Any]) -> bytes:
    """UTF-8 canonical JSON for a reproducible checksum; reject NaN/Infinity."""
    return json.dumps(payload, ensure_ascii=False, allow_nan=False,
                      sort_keys=True, separators=(",", ":")).encode("utf-8")


def check_packet_integrity(packet: dict[str, Any]) -> bool:
    """Self-check only. A SHA-256 digest is NOT an author signature or notarization."""
    if not isinstance(packet, dict):
        return False
    tag = packet.get("packetIntegrity")
    if not isinstance(tag, dict) or tag.get("algorithm") != "SHA-256":
        return False
    fingerprint = tag.get("digest")
    if not isinstance(fingerprint, str) or len(fingerprint) != 64:
        return False
    body = {k: v for k, v in packet.items() if k != "packetIntegrity"}
    return hashlib.sha256(canonical_bytes(body)).hexdigest() == fingerprint


def build_review_packet(nct_id: str, *, generated_at: datetime | None = None) -> dict:
    """Read verified archive and ledger. Return a portable, non-adjudicated dossier.

    The authenticated API handles HTTP status codes. If archive, NCT identity,
    or evidence ledger integrity fails, propagate the failure and emit no packet.
    """
    if not isinstance(nct_id, str) or not NCT_PATTERN.fullmatch(nct_id):
        raise ValueError("Exact NCT identifier required")
    with Session(main.ENGINE) as session:
        stored = session.get(main.FullTrialRecord, nct_id)
        if stored is None:
            raise LookupError("No archived trial exists for this exact NCT identifier")
        raw = verified_record_from_archive(nct_id, stored.payload_gzip, stored.sha256)
        digest = stored.sha256
        retrieved = (stored.fetched_at.isoformat() if stored.fetched_at else None)

    # Evidence entries are validated in the read_ledger path. Fail CLOSED for
    # tampered rows rather than returning a dossier that omits a conflict.
    ledger = read_ledger(nct_id)
    coverage = investigation_20(nct_id, raw, retrieved_at=retrieved)
    assessment_stage_crosswalk = stage_crosswalk(coverage)
    numbers = reported_quantitative_results(nct_id, raw)
    grades = review_readiness(nct_id, raw, archive_retrieved_at=retrieved)
    worklist = ledger["sourceReconciliation"]
    reviewer_summary = {
        item["questionId"]: item
        for item in ledger["reviewerFindings"]["questionSummaries"]
    }
    checks = []
    for check in worklist["checks"]:
        item = dict(check)
        summary = reviewer_summary.get(check["id"], {})
        item["reviewerStatementCount"] = summary.get("statementCount", 0)
        item["conflictingReviewerStatements"] = summary.get(
            "conflictingReviewerStatements", False
        )
        item["resolutionCriteria"] = list(PILOT_ACCEPTANCE.get(
            check["id"], (
                "Review dated original source and its exact clinical indication.",
                "Extract the relevant method, evidence and potential conflicting data.",
                "Obtain an independent reviewer assessment and resolve contradictions.",
            ),
        ))
        item["criteriaSatisfied"] = 0
        item["reviewerAttestation"] = None
        item["resolutionEvidence"] = []
        item["resolved"] = False
        checks.append(item)
    assert all(item["resolved"] is False for item in checks)
    packet_date = generated_at or datetime.now(timezone.utc)
    if packet_date.tzinfo is None:
        raise ValueError("Packet timestamp must have timezone")
    packet = {
        "packetSchemaVersion": PACKET_SCHEMA_VERSION,
        "nctId": nct_id,
        "generatedAtUtc": packet_date.astimezone(timezone.utc).isoformat(),
        "purpose": "source_review_packet_not_independent_scientific_adjudication",
        "archive": {
            "nctId": nct_id,
            "sourceUrl": "https://clinicaltrials.gov/study/" + nct_id,
            "sourceType": "archived_clinicaltrials_gov_api_v2",
            "retrievedAt": retrieved,
            "sha256": digest,
            "archiveIdentityAndSha256Verified": True,
        },
        "registryEvidence": extract_trial_evidence(nct_id, raw),
        "investigation20": coverage,
        "assessmentStageCrosswalk": assessment_stage_crosswalk,
        "quantitativeResults": numbers,
        "evidenceInputGrades": grades,
        "independentSourceLedger": ledger,
        "adjudicationPreflight": ledger["adjudicationPreflight"],
        "reconciliation": {
            "scope": worklist["scope"],
            "unresolvedCount": len(checks),
            "independentlyResolvedCount": 0,
            "checks": checks,
            "reviewerAttestationsLoaded": False,
        },
        "reviewLimitations": [
            "Archived registry content is a dated snapshot, not necessarily the current record.",
            "Source citations, numerical reports, and source coverage are not independent scientific appraisal.",
            "A source checklist cannot substitute for protocol/SAP, multiplicity, safety and FDA document reconciliation.",
            "All evidence conflicts remain open until an authorized, auditable independent review.",
            "This packet is not evidence of a drug's success/failure and must not inform trading orders.",
        ],
        "scientificConclusion": None,
        "scientificallyVerified": False,
        "fdaApprovalProbability": None,
        "readyForFullScientificConclusion": False,
        "tradingEnabled": False,
    }
    packet["packetIntegrity"] = {
        "algorithm": "SHA-256",
        "canonicalization": "UTF-8 JSON sorted keys with compact separators, excluding packetIntegrity",
        "digest": hashlib.sha256(canonical_bytes(packet)).hexdigest(),
        "note": "Integrity checksum only; not digital signing, source authenticity or adjudication.",
    }
    return packet
